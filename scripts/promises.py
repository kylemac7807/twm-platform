"""Write tests/PROMISES.md: every test, in plain English, grouped by the area it protects (test strategy, decided Oct 13, 2026).

    .venv/Scripts/python.exe scripts/promises.py

A test's promise is its docstring's first line when it has one, otherwise its name turned into words. The pre-commit hook
regenerates this file whenever tests/ changes, so the list can never be stale. Kyle reads it and adds promises in plain
language; each new line becomes a test.
"""
import ast
import re
import sys
from datetime import date
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
ROOT = Path(__file__).resolve().parents[1]
TESTS = ROOT / "tests"
OUT = TESTS / "PROMISES.md"
NL = chr(10)

AREAS = {  # test file -> the area, in the words of the design record
    "test_normalize.py": "Normalization: titles to roles and bands",
    "test_location.py": "Location: place names are flagged, never guessed",
    "test_taxonomy.py": "The Role Framework tables",
    "test_acceptance.py": "The acceptance report",
    "test_ingest.py": "Intake: what a document really is and which contract set it belongs to",
    "test_read.py": "Document reading: positions, tables, quality",
    "test_llm.py": "The model wrapper: validation, retry, cache",
    "test_extract.py": "Extraction: every number verified on the page",
    "test_resolve_model.py": "The model step of normalization: what the model may not do",
    "test_ledger.py": "The ledger and the analyst's decisions",
    "test_workbench.py": "The review workbench",
    "test_regression.py": "Regression: whole documents give the same answer as before",
    "test_contract_terms.py": "Contract terms: the fine print beside the rates, verified on the page",
}


def words(name: str) -> str:
    s = name[len("test_"):] if name.startswith("test_") else name
    s = s.replace("_", " ")
    s = re.sub(r"\b(gc15|gcloud)\b", "G-Cloud", s)
    return s[:1].upper() + s[1:]


def promises_for(path: Path) -> list[tuple[str, str, int]]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    out = []
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
            doc = ast.get_docstring(node)
            text = doc.strip().splitlines()[0].strip() if doc else words(node.name)
            out.append((text, node.name, node.lineno))
    return out


def main() -> int:
    files = sorted(TESTS.glob("test_*.py"), key=lambda p: list(AREAS).index(p.name) if p.name in AREAS else 99)
    total = 0
    L = ["# What the tests promise", "",
         f"Generated by `scripts/promises.py` on {date.today().isoformat()}; regenerated by the pre-commit hook whenever `tests/` changes. "
         "One line per test, in plain English, grouped by the area it protects. The rules (docs/how-we-build.md): every decision becomes a test "
         "named after it; every bug becomes a test; every document run becomes a regression check. Add a promise here in plain language and "
         "Claude turns it into a test.", ""]
    for f in files:
        ps = promises_for(f)
        if not ps:
            continue
        total += len(ps)
        L += [f"## {AREAS.get(f.name, f.name)}  ·  `tests/{f.name}` ({len(ps)})", ""]
        for text, name, line in ps:
            L.append(f"- {text}  <sub>`{name}` line {line}</sub>")
        L.append("")
    L.insert(2, f"**{total} promises** in {len([f for f in files if promises_for(f)])} files.")
    L.insert(3, "")
    OUT.write_text(NL.join(L) + NL, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {total} promises")
    return 0


if __name__ == "__main__":
    sys.exit(main())
